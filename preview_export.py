"""Export the actual reader's fictional demo as a portable private review snapshot."""
import argparse
from tempfile import TemporaryDirectory
import json
from pathlib import Path

from app import create_app
from demo import seed
from publishing import open_reader
from reader import layout

STORY = 'fictional-bus-pilot'
BANNER = '''<aside style="padding:14px 24px;background:#18382c;color:white;font:15px/1.5 system-ui;text-align:center">
<strong>Reader test · fictional news sample</strong> — Snapshot generated by the EPSTMC application.
<a style="color:white;margin-left:12px" href="/workflow/">Explore the workflow</a></aside>'''


def write_json(path, payload):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')


def export(destination):
    destination = Path(destination)
    destination.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory(prefix='epstmc-review-') as tmp:
        db = Path(tmp) / 'demo.sqlite'
        seed(db)
        app = create_app(db)
        with open_reader(db) as reader:
            feed = reader.feed()
            story = reader.story(STORY)
            history = reader.history(STORY)
        write_json(destination/'data/feed.json', feed)
        write_json(destination/f'data/{STORY}.json', story)
        write_json(destination/'data/history.json', history)
        for item in history['versions']:
            write_json(destination/f'data/versions/{item["version"]}.json', item)

        def rewrite(html):
            html = html.replace('<body>', '<body>'+BANNER)
            html = html.replace('href="/api/v1/feed"', 'href="/data/feed.json"')
            for version in (1, 2):
                html = html.replace(f'href="/stories/{STORY}?version={version}"',
                                    f'href="/stories/{STORY}/versions/{version}/"')
                html = html.replace(f'href="/api/v1/stories/{STORY}/versions/{version}"',
                                    f'href="/data/versions/{version}.json"')
            return html.replace(f'href="/stories/{STORY}"', f'href="/stories/{STORY}/"')

        for path, query, output in (
            ('/', '', 'index.html'),
            (f'/stories/{STORY}', '', f'stories/{STORY}/index.html'),
            (f'/stories/{STORY}', 'version=1', f'stories/{STORY}/versions/1/index.html'),
            (f'/stories/{STORY}', 'version=2', f'stories/{STORY}/versions/2/index.html'),
        ):
            captured = {}
            def start(status, headers):
                captured['status'] = status
            body = b''.join(app({'PATH_INFO': path, 'REQUEST_METHOD': 'GET', 'QUERY_STRING': query}, start))
            if captured['status'] != '200 OK':
                raise ValueError(f'Reader export failed: {captured["status"]}')
            target = destination/output
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(rewrite(body.decode()), encoding='utf-8')

        workflow = '''<h1>Test one story, end to end</h1>
<p>This private review snapshot uses the real application renderer and a temporary demo database.
The council story and evidence are fictional. It demonstrates reading and publication history;
the editorial workflow currently runs through trusted command-line tools.</p>
<h2>Try the reader</h2><ol>
<li><a href="/">Open the feed</a> and select the story.</li>
<li><a href="/stories/fictional-bus-pilot/versions/1/">Read the original publication</a>: the proposal covers two routes.</li>
<li><a href="/stories/fictional-bus-pilot/">Read the correction</a>: the fictional proposal covers three routes.</li>
<li>Inspect the original sources, comparison limitations, scenario trigger, timeframe and signal.</li>
<li>Use publication history to revisit the earlier wording and find the correction explanation.</li></ol>
<h2>Workflow exercised to produce this sample</h2>
<table style="width:100%;border-collapse:collapse"><thead><tr><th align="left">Stage</th><th align="left">Recorded result</th></tr></thead>
<tbody><tr><td>Evidence registration</td><td>Current proposal and historical archive attached</td></tr>
<tr><td>Draft</td><td>Facts, historical comparison and conditional scenario stored</td></tr>
<tr><td>Review</td><td>Fictional review submitted and approved</td></tr>
<tr><td>Initial publication</td><td>Version 1 appears in the reader</td></tr>
<tr><td>Revision and review</td><td>Version 2 approved separately</td></tr>
<tr><td>Correction</td><td>Version 2 is current; version 1 stays readable</td></tr></tbody></table>
<h2>Inspect the public data</h2><p>
<a href="/data/feed.json">Feed JSON</a> · <a href="/data/history.json">Publication history JSON</a></p>
<h2>Current test boundary</h2><p>This is a fixed reader snapshot. Draft creation, approval and publishing
are not browser controls yet. Source links point to example.com placeholders.
Live source intake, a hosted database and ongoing news refresh are not connected to this review site.</p>'''
        target = destination/'workflow/index.html'
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(rewrite(layout('Workflow test', workflow)), encoding='utf-8')
        return {'story_id': STORY, 'published_versions': len(history['versions']), 'output': str(destination)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(export(args.output)))


if __name__ == '__main__':
    main()
